"""Generate/check static frontend display metadata; no configuration or DB access.

Run from backend: .venv/bin/python -m scripts.export_spec_display [--check]
"""

import argparse
import json
from pathlib import Path

from app.tools.catalog.fields import CATEGORY_ALIASES
from app.tools.catalog.spec_display import display_registry

TARGET = Path(__file__).resolve().parents[2] / "frontend/src/generated/spec-display.ts"


def generated_source() -> str:
    registry = json.dumps(display_registry(), ensure_ascii=False, indent=2)
    aliases = json.dumps(CATEGORY_ALIASES, ensure_ascii=False, indent=2)
    return (
        "// Generated by backend/scripts/export_spec_display.py; do not edit.\n"
        "export type SpecDisplayDefinition = { label: string; unit: string; "
        "categoryLabels: Record<string, string>; values: Record<string, string> };\n"
        f"export const specDisplayRegistry: Record<string, SpecDisplayDefinition> = {registry};\n"
        f"export const specCategoryAliases: Record<string, string> = {aliases};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generated_source()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != source:
            raise SystemExit("Specification display dictionary is stale; run make spec-display.")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(source)


if __name__ == "__main__":
    main()
